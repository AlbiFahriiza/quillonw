#!/usr/bin/env python3
"""Bakes the COMING SOON letter outlines into lib/coming-soon-paths.ts.

Run from the repo root:  pip install fonttools skia-pathops && python3 scripts/extract-glyphs.py
The four fonts are the ones the hero used to swap between (all OFL, from google/fonts).
Each font's line is laid out into one shared viewBox with the same total width, so
morphing between fonts never changes the layout. The output is committed; the font
files are downloaded to a temp dir and never kept.
"""
import io, os, sys, tempfile, urllib.request
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

RAW = "https://raw.githubusercontent.com/google/fonts/main/ofl"
FONTS = [  # order = the order the hero cycles through them
    ("Space Grotesk 700", f"{RAW}/spacegrotesk/SpaceGrotesk%5Bwght%5D.ttf", {"wght": 700}),
    ("Playfair Display Italic 700", f"{RAW}/playfairdisplay/PlayfairDisplay-Italic%5Bwght%5D.ttf", {"wght": 700}),
    ("Space Mono 700", f"{RAW}/spacemono/SpaceMono-Bold.ttf", None),
    ("Bungee 400", f"{RAW}/bungee/Bungee-Regular.ttf", None),
]
WORDS = ["COMING", "SOON"]
VIEW_W, VIEW_H, BASELINE = 1000, 146, 118
WORD_GAP, STAR_W = 40, 64          # viewBox units
LETTER_GAP_EM = 0.06                # same tracking the CSS version used

def load(url, axes):
    cache = os.path.join(tempfile.gettempdir(), os.path.basename(url).replace("%5B", "[").replace("%5D", "]"))
    if not os.path.exists(cache):
        with urllib.request.urlopen(url) as r, open(cache, "wb") as f:
            f.write(r.read())
    font = TTFont(cache)
    if axes:
        # REMOVE merges the overlapping contours variable fonts keep, so every
        # letter morphs as one clean shape.
        font = instancer.instantiateVariableFont(font, axes, overlap=instancer.OverlapMode.REMOVE)
    return font

def layout(font):
    cmap, hmtx, upm = font.getBestCmap(), font["hmtx"], font["head"].unitsPerEm
    gs = font.getGlyphSet()
    advances = [[hmtx[cmap[ord(c)]][0] / upm for c in w] for w in WORDS]
    em_width = sum(map(sum, advances)) + LETTER_GAP_EM * sum(len(w) - 1 for w in WORDS)
    scale = (VIEW_W - 2 * WORD_GAP - STAR_W) / em_width      # units per em
    paths, centers, x = [], [], 0.0
    for wi, word in enumerate(WORDS):
        for li, ch in enumerate(word):
            name, adv = cmap[ord(ch)], advances[wi][li]
            pen = SVGPathPen(gs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
            # font space is y-up; flip and move the glyph onto the shared baseline
            gs[name].draw(TransformPen(pen, (scale / upm, 0, 0, -scale / upm, x, BASELINE)))
            paths.append(pen.getCommands())
            centers.append(round(x + adv * scale / 2, 1))
            x += (adv + LETTER_GAP_EM) * scale
        x += WORD_GAP - LETTER_GAP_EM * scale
    return paths, centers

def main():
    all_paths, all_centers = [], []
    for label, url, axes in FONTS:
        paths, centers = layout(load(url, axes))
        all_paths.append(paths); all_centers.append(centers)
        print(label, "contours per glyph:", [p.count("M") for p in paths], file=sys.stderr)
    centers = [round(sum(c[i] for c in all_centers) / len(all_centers), 1) for i in range(len(all_centers[0]))]
    out = io.StringIO()
    out.write("// Generated by scripts/extract-glyphs.py. Do not edit by hand.\n")
    out.write("// Fonts: " + ", ".join(f[0] for f in FONTS) + " (all SIL OFL).\n\n")
    out.write(f"export const VIEWBOX = {{ width: {VIEW_W}, height: {VIEW_H}, baseline: {BASELINE} }} as const;\n")
    out.write(f"export const STAR = {{ x: {VIEW_W - STAR_W / 2:.0f}, y: {BASELINE - 38}, size: {STAR_W} }} as const;\n")
    out.write(f"export const FONT_LABELS = {[f[0] for f in FONTS]!r} as const;\n".replace("'", '"'))
    out.write(f"export const GLYPH_CENTERS: readonly number[] = {centers};\n\n")
    out.write("// GLYPH_PATHS[font][glyph]: C O M I N G S O O N, already positioned in the viewBox.\n")
    out.write("export const GLYPH_PATHS: readonly (readonly string[])[] = [\n")
    for paths in all_paths:
        out.write("  [\n" + "".join(f'    "{p}",\n' for p in paths) + "  ],\n")
    out.write("];\n")
    dest = os.path.join(os.path.dirname(__file__), "..", "lib", "coming-soon-paths.ts")
    open(dest, "w").write(out.getvalue())
    print("wrote", os.path.normpath(dest), len(out.getvalue()), "bytes", file=sys.stderr)

main()
